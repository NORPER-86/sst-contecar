-- ==========================================================
-- Esquema Oficial de Base de Datos para Supabase (CONTECAR / SPRC - SURA)
-- Tabla 'observaciones' con soporte JSON y Gobernanza SST
-- ==========================================================

create table if not exists observaciones (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  fecha_realizacion text not null,
  terminal text not null default 'CTC',
  area text not null default 'Administración de Operaciones',
  observador text not null default 'N/A',
  empresa_ejecutante text not null default 'N/A',
  pcp_calculado numeric not null default 0.0,
  categoria text not null default 'D',
  raw_data jsonb
);

-- Índices de alto rendimiento para el Tablero Analítico (BI)
create index if not exists idx_observaciones_fecha on observaciones(fecha_realizacion);
create index if not exists idx_observaciones_area on observaciones(area);
create index if not exists idx_observaciones_categoria on observaciones(categoria);

-- Configuración de Políticas de Seguridad (Row Level Security - RLS)
alter table observaciones enable row level security;

-- Permitir lectura a clientes autenticados y con clave anónima (Dashboard BI)
create policy "Permitir lectura publica" 
  on observaciones for select 
  using (true);

-- Permitir inserción desde la aplicación (Ingesta OCR)
create policy "Permitir insercion publica" 
  on observaciones for insert 
  with check (true);
